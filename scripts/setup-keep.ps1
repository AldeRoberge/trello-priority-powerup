# Adds the "Documents <-> Google Keep" sync to an already installed Sheet sync Worker.
#
#   powershell -ExecutionPolicy Bypass -File .\scripts\setup-keep.ps1
#   (or: npm run setup:keep)
#
# Google Workspace only: the Keep API refuses personal Gmail accounts. Run
# scripts/setup-sheet-sync.ps1 first. This script:
#   1 account   asks for your Workspace email (the Keep notes owner)
#   2 admin     shows the Client ID + scope a Workspace admin must authorize (domain-wide delegation)
#   3 deploy    saves KEEP_USER_EMAIL (and KEEP_LISTS) as Worker secrets and redeploys the Worker
#   4 sync      runs the first pass and tells you whether Keep accepted it
#
# Resumable and idempotent: re-run the same command. -Reset forgets the saved email and lists only.

param(
  [switch]$Reset
)

$ErrorActionPreference = "Stop"
try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8; $OutputEncoding = [System.Text.Encoding]::UTF8 } catch {}

$RepoRoot = Split-Path -Parent $PSScriptRoot
$WorkerDir = Join-Path $RepoRoot "workers\trello-sheet-sync"
$StatePath = Join-Path $WorkerDir ".setup-state.json"
$DevVarsPath = Join-Path $WorkerDir ".dev.vars"
$KeyPath = Join-Path $WorkerDir ".sa-key.json"
$DefaultLists = "To sell/to buy|Todo in Rouyn|Things to pack for Cottage"

function Write-Step([string]$Text) { Write-Host "`n== $Text ==" -ForegroundColor Cyan }
function Write-Info([string]$Text) { Write-Host "  $Text" -ForegroundColor DarkGray }

function Read-DevVars {
  $vars = [ordered]@{}
  if (Test-Path $DevVarsPath) {
    foreach ($line in Get-Content $DevVarsPath) {
      if ($line -match '^\s*([A-Z0-9_]+)=(.*)$') { $vars[$Matches[1]] = $Matches[2] }
    }
  }
  return $vars
}

function Write-DevVars($vars) {
  $lines = @("# Generated by scripts/setup-sheet-sync.ps1. Gitignored - never commit.")
  foreach ($k in $vars.Keys) { $lines += "$k=$($vars[$k])" }
  Set-Content -Path $DevVarsPath -Value ($lines -join "`n") -NoNewline
}

# Runs a native command with stderr noise tolerated; returns its exit code only.
function Invoke-Native([scriptblock]$Command) {
  $prev = $ErrorActionPreference
  $ErrorActionPreference = "Continue"
  try { & $Command | Out-Host; return [int]$LASTEXITCODE } finally { $ErrorActionPreference = $prev }
}

# A plain email address, or $null (the user once pasted a whole command as an answer).
function ConvertTo-Email([string]$Text) {
  $t = "$Text".Trim().Trim('"').Trim("'")
  if ($t -match '^[^\s@]+@[^\s@]+\.[^\s@]+$') { return $t }
  return $null
}

# "a|b|c" with blanks removed; $null when nothing usable is left. A pasted command (";", "&", "npm") is refused.
function ConvertTo-KeepLists([string]$Text) {
  $t = "$Text".Trim()
  if ($t -match '[;&`$]' -or $t -match '^(npm|npx|powershell|git)\b') { return $null }
  $parts = @($t -split '\|' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
  if ($parts.Count -eq 0) { return $null }
  return ($parts -join '|')
}

function Invoke-Worker([string]$Method, [string]$Path) {
  $vars = Read-DevVars
  return Invoke-RestMethod -Method $Method -Uri ($script:State.workerUrl.TrimEnd('/') + $Path) -Headers @{ "x-sync-secret" = $vars['SYNC_SECRET'] } -TimeoutSec 120
}

# ---------------------------------------------------------------- checks --------------------------------------------
if (-not (Test-Path $StatePath) -or -not (Test-Path $DevVarsPath)) {
  throw "The Sheet sync is not installed yet. Run: npm run setup:sheet-sync"
}
$State = @{}
(Get-Content -Raw $StatePath | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $State[$_.Name] = $_.Value }
function Save-State { $script:State | ConvertTo-Json -Depth 5 | Set-Content -Path $StatePath -Encoding UTF8 }
if (-not $State.workerUrl) { throw "No Worker URL in $StatePath. Finish the Sheet sync setup first: npm run setup:sheet-sync" }

if ($Reset) { $State.Remove('keepEmail'); $State.Remove('keepLists'); Save-State }

# Self-heal a bad saved value
if ($State.keepEmail -and -not (ConvertTo-Email $State.keepEmail)) { $State.Remove('keepEmail'); Save-State }
if ($State.keepLists -and -not (ConvertTo-KeepLists $State.keepLists)) { $State.Remove('keepLists'); Save-State }

# ---------------------------------------------------------------- 1 account -----------------------------------------
Write-Step "1/4 Workspace account"
if (-not $State.keepEmail) {
  while ($true) {
    $typed = Read-Host "  Your Google Workspace email (the account that owns the Keep notes)"
    $email = ConvertTo-Email $typed
    if ($email) { $State.keepEmail = $email; break }
    Write-Host "  That is not an email address. Try again." -ForegroundColor Yellow
  }
  Save-State
}
Write-Info "Account: $($State.keepEmail)"

if (-not $State.keepLists) {
  Write-Info "Notes to sync, separated by |. Enter = $DefaultLists"
  Write-Info "(Lists named 'To bring to ...' are always synced.)"
  while ($true) {
    $typed = Read-Host "  Note titles"
    if ([string]::IsNullOrWhiteSpace($typed)) { $State.keepLists = $DefaultLists; break }
    $lists = ConvertTo-KeepLists $typed
    if ($lists) { $State.keepLists = $lists; break }
    Write-Host "  That does not look like note titles. Try again, or press Enter." -ForegroundColor Yellow
  }
  Save-State
}
Write-Info "Notes: $($State.keepLists)"

# ---------------------------------------------------------------- 2 admin -------------------------------------------
Write-Step "2/4 Workspace admin authorization"
$clientId = ""
if (Test-Path $KeyPath) {
  try { $clientId = "$((Get-Content -Raw $KeyPath | ConvertFrom-Json).client_id)" } catch { $clientId = "" }
}
if (-not $clientId) {
  $vars = Read-DevVars
  Write-Info "Service account key file not found. Use the numeric Client ID of $($vars['GOOGLE_SERVICE_ACCOUNT_EMAIL']) (Google Cloud > IAM > Service accounts > Details)."
  $clientId = "<Client ID du compte de service>"
}
Write-Host "  A Workspace admin must do this once:" -ForegroundColor Yellow
Write-Host "    1. Google Cloud: enable the 'Google Keep API' on the project of the service account"
Write-Host "    2. admin.google.com > Security > Access and data control > API controls > Manage domain-wide delegation > Add new"
Write-Host "         Client ID : $clientId"
Write-Host "         Scope     : https://www.googleapis.com/auth/keep"
if ($State.done_keep_admin -ne $true) {
  $null = Read-Host "  Press Enter when it is done"
  $State.done_keep_admin = $true
  Save-State
}

# ---------------------------------------------------------------- 3 deploy ------------------------------------------
Write-Step "3/4 Saving the secrets and redeploying the Worker"
$vars = Read-DevVars
$vars['KEEP_USER_EMAIL'] = $State.keepEmail
$vars['KEEP_LISTS'] = $State.keepLists
Write-DevVars $vars
$bulk = Join-Path $env:TEMP ("secrets-" + [guid]::NewGuid().ToString("N") + ".json")
Push-Location $WorkerDir
try {
  # Deploy first: a Worker that does not know the secrets yet just ignores them.
  if ((Invoke-Native { npx --yes wrangler deploy }) -ne 0) { throw "wrangler deploy failed" }
  (@{ KEEP_USER_EMAIL = $State.keepEmail; KEEP_LISTS = $State.keepLists } | ConvertTo-Json) | Set-Content -Path $bulk -Encoding UTF8
  if ((Invoke-Native { npx --yes wrangler secret bulk $bulk }) -ne 0) { throw "wrangler secret bulk failed" }
} finally {
  Remove-Item $bulk -Force -ErrorAction SilentlyContinue
  Pop-Location
}

# ---------------------------------------------------------------- 4 first sync --------------------------------------
Write-Step "4/4 First Keep pass"
Start-Sleep -Seconds 5
$result = $null
for ($attempt = 1; $attempt -le 3; $attempt++) {
  try { $result = Invoke-Worker "Post" "/keep/sync"; break } catch {
    if ($attempt -eq 3) { throw }
    Start-Sleep -Seconds 8
  }
}
if ($result.error) {
  Write-Host "  The Worker could not reach Keep:" -ForegroundColor Red
  Write-Host "  $($result.error)" -ForegroundColor Red
  Write-Host "  Fix it (usually the admin authorization, which can take a few minutes), then run the same command again:" -ForegroundColor Yellow
  Write-Host "    npm run setup:keep" -ForegroundColor Yellow
  exit 1
}
Write-Host ("  {0} document(s): {1} created, {2} updated, {3} pulled from Keep, {4} imported, {5} unchanged" -f $result.documents, $result.created, $result.updated, $result.pulled, $result.imported, $result.unchanged) -ForegroundColor Green
Write-Host "`nDone. Tracked documents and Keep notes now follow each other." -ForegroundColor Green
